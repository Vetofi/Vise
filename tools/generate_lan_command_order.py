#!/usr/bin/env python3
import json
import os
import subprocess
import sys

try:
    from . import lab, test_rust_parity as base
except ImportError:
    import lab
    import test_rust_parity as base

OUT = lab.ROOT / 'crates/vise-client/src/lan/command_order.rs'


def main():
    lock, jars, libraries = base.verify_artifacts()
    build = lab.LOCAL / 'lan-command-order'
    classes = build / 'classes'
    classes.mkdir(parents=True, exist_ok=True)
    oracle = lab.ROOT / 'mods/vise/src/test/java/dev/viselab/parity/VanillaCommandParseOracle.java'
    path = os.pathsep.join(map(str, [jars['server'], *libraries]))
    subprocess.run(['javac', '--release', str(lock['minecraft']['java_major']), '-proc:none', '-cp', path,
                    '-d', str(classes), str(oracle)], check=True)
    subprocess.run(['java', '-Xmx1G', '-cp', str(classes) + os.pathsep + path,
                    'dev.viselab.parity.VanillaCommandParseOracle', 'tree', str(build), 'ALL'],
                   check=True, cwd=build, stdout=subprocess.DEVNULL)
    tree = json.loads((build / 'tree.json').read_text())
    rows = []

    def walk(node, path):
        names = list(node.get('children', {}))
        if len(names) > 1 and path != ['gamerule']:
            rows.append((' '.join(path), ' '.join(names)))
        for name in names:
            walk(node['children'][name], path + [name])

    walk(tree, [])
    lines = [
        '//! The order of the children of each node of vanilla\'s command tree',
        '//! (path of node names from the root, children in registration order),',
        '//! for nodes with several children. Generated by',
        '//! tools/generate_lan_command_order.py; do not edit by hand.',
        '',
        'pub const ORDER: &[(&str, &str)] = &[',
    ]
    lines += [f'    ("{p}", "{n}"),' for p, n in rows]
    lines += ['];', '']
    OUT.write_text('\n'.join(lines))
    print(f'wrote {len(rows)} nodes to {OUT}')


if __name__ == '__main__':
    sys.exit(main())
